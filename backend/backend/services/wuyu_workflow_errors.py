MATERIAL_PARSE_CODES = frozenset(('archive_limit', 'encrypted_material', 'image_limit', 'invalid_csv', 'invalid_encoding', 'invalid_image', 'invalid_office', 'invalid_pdf', 'logo_format', 'material_limit', 'material_not_found', 'material_timeout', 'template_render_failed', 'unsafe_archive', 'unsafe_path', 'unsupported_material'))


def material_error_code(code):
    """Project only known local-parser codes; never expose arbitrary upstream values."""
    value = code.lower() if isinstance(code, str) else ''
    if value in {'material_project_limit', 'material_project_capacity'}:
        return 'MATERIAL_PROJECT_LIMIT'
    return value if value in MATERIAL_PARSE_CODES else 'MATERIAL_PARSE_FAILED'


def material_parse_error_code(error):
    """Only typed parser errors may preserve a known code; message text is unused."""
    return material_error_code(error.code) if isinstance(error, PipelineError) else 'MATERIAL_PARSE_FAILED'
